                "# 7. Fine-Tuning Routine for Flat/Plains Events\n",
                "def fine_tune(model, train_loader, val_loader, epochs=5, lr=5e-5, device=device):\n",
                "    # Class-weighted CrossEntropy to counter flood imbalance\n",
                "    weights = torch.tensor([0.37, 14.0, 8.2], dtype=torch.float32).to(device)\n",
                "    criterion = nn.CrossEntropyLoss(weight=weights)\n",
                "    optimizer = torch.optim.AdamW(model.parameters(), lr=lr, weight_decay=1e-4)\n",
                "    scheduler = torch.optim.lr_scheduler.CosineAnnealingLR(optimizer, T_max=epochs, eta_min=1e-6)\n",
                "\n",
                "    best_f1 = 0.0\n",
                "    for ep in range(epochs):\n",
                "        model.train()\n",
                "        loss_sum = 0.0\n",
                "        t0 = time.time()\n",
                "        for xA, xB, labels, _ in train_loader:\n",
                "            xA, xB, labels = xA.to(device), xB.to(device), labels.to(device)\n",
                "            optimizer.zero_grad()\n",
                "            out = model(xA, xB)\n",
                "            loss = criterion(out, labels)\n",
                "            loss.backward()\n",
                "            optimizer.step()\n",
                "            loss_sum += loss.item()\n",
                "        scheduler.step()\n",
                "        print(f'Epoch [{ep+1}/{epochs}] Loss: {loss_sum/len(train_loader):.4f} | Time: {time.time()-t0:.1f}s')\n",
                "        _, val_res = evaluate_events(model, val_loader, device=device, name=f'Val Epoch {ep+1}')\n",
                "        if val_res['f1'] > best_f1:\n",
                "            best_f1 = val_res['f1']\n",
                "            torch.save(model.state_dict(), '/content/weights/best_finetuned_snunet.pt')\n",
                "            print(f'--> Checkpoint saved with Val F1: {best_f1:.4f}')\n",
                "    print('Fine-tuning complete. Best Val F1:', best_f1)\n"
