                "                        continue\n",
                "                    actid = int(actid)\n",
                "                    if allowed_acts is not None and actid not in allowed_acts:\n",
                "                        continue\n",
                "                    self.samples.append((p, actid))\n",
                "                    event_counts[actid] = event_counts.get(actid, 0) + 1\n",
