                "\n",
                "        x3_1 = self.conv3_1(torch.cat([x3_0A, x3_0B, self.Up(x4_0B)], 1))\n",
                "        x2_2 = self.conv2_2(torch.cat([x2_0A, x2_0B, x2_1, self.Up(x3_1)], 1))\n",
                "        x1_3 = self.conv1_3(torch.cat([x1_0A, x1_0B, x1_1, x1_2, self.Up(x2_2)], 1))\n",
                "        x0_4 = self.conv0_4(torch.cat([x0_0A, x0_0B, x0_1, x0_2, x0_3, self.Up(x1_3)], 1))\n",
                "\n",
                "        out = torch.cat([x0_1, x0_2, x0_3, x0_4], 1)\n",
                "        intra = torch.sum(torch.stack((x0_1, x0_2, x0_3, x0_4)), dim=0)\n",
                "        ca1 = self.ca1(intra)\n",
