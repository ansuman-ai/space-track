                "TEST_ACTS  = {321, 561, 445, 562, 411, 1111002, 277, 1111007, 205, 1111013}\n",
                "\n",
                "def preprocess_branch(vv, vh, slope=None):\n",
                "    vv_lin = np.clip(vv, 0.0, CLAMP_MAX)\n",
                "    vh_lin = np.clip(vh, 0.0, CLAMP_MAX)\n",
                "    s1 = np.stack([vv_lin, vh_lin], axis=0)\n",
                "    s1_norm = (s1 - DATA_MEAN) / DATA_STD\n",
                "    if slope is not None:\n",
                "        slope_norm = ((slope - SLOPE_MEAN) / SLOPE_STD)[np.newaxis, :, :]\n",
                "    else:\n",
                "        slope_norm = np.zeros((1, vv.shape[0], vv.shape[1]), dtype=np.float32)\n",
                "    return np.concatenate([s1_norm, slope_norm], axis=0).astype(np.float32)\n"
