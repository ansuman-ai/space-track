                "# 5. Preprocessing & Event-Partitioned Data Loader\n",
                "DATA_MEAN = np.array([0.0953, 0.0264], dtype=np.float32).reshape(2, 1, 1)\n",
                "DATA_STD = np.array([0.0427, 0.0215], dtype=np.float32).reshape(2, 1, 1)\n",
                "SLOPE_MEAN = 2.1277\n",
                "SLOPE_STD = 67.5048\n",
                "CLAMP_MAX = 0.15\n",
                "\n",
                "# Official Split by Event IDs (actid)\n",
                "TRAIN_ACTS = {130, 470, 555, 118, 174, 324, 421, 554, 427, 518, 502, 498, 497, 496, 492, 147, 267, 273, 275, 417, 567, 1111011, 1111004, 1111009, 1111010, 1111006, 1111005}\n",
