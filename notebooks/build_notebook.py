                "# 6. Evaluation Function (Reporting Per-Event IoU, F1, Precision, Recall)\n",
                "def evaluate_events(model, dataloader, device=device, name='Evaluation'):\n",
                "    model.eval()\n",
                "    event_stats = {}\n",
                "    tot_tp, tot_fp, tot_fn = 0, 0, 0\n",
                "    with torch.no_grad():\n",
                "        for xA, xB, labels, actids in dataloader:\n",
                "            xA, xB = xA.to(device), xB.to(device)\n",
                "            logits = model(xA, xB)\n",
                "            preds = torch.argmax(logits, dim=1).cpu().numpy()\n",
                "            labels = labels.numpy()\n",
                "            actids = actids.numpy()\n",
                "            for i in range(len(preds)):\n",
                "                act = int(actids[i])\n",
                "                if act not in event_stats:\n",
                "                    event_stats[act] = {'tp': 0, 'fp': 0, 'fn': 0}\n",
                "                p_flood = (preds[i] == 2)\n",
                "                l_flood = (labels[i] == 2)\n",
                "                tp = int(np.sum(p_flood & l_flood))\n",
                "                fp = int(np.sum(p_flood & ~l_flood))\n",
                "                fn = int(np.sum(~p_flood & l_flood))\n",
                "                event_stats[act]['tp'] += tp\n",
                "                event_stats[act]['fp'] += fp\n",
                "                event_stats[act]['fn'] += fn\n",
                "                tot_tp += tp; tot_fp += fp; tot_fn += fn\n",
                "\n",
                "    print(f'\\n=== {name} Per-Event Flood Metrics (Argmax) ===')\n",
                "    print(f'{\"Event ID\":<12} | {\"IoU\":<8} | {\"F1\":<8} | {\"Precision\":<10} | {\"Recall\":<8}')\n",
                "    print('-' * 56)\n",
                "    results = {}\n",
                "    for act, s in sorted(event_stats.items()):\n",
                "        tp, fp, fn = s['tp'], s['fp'], s['fn']\n",
                "        iou = tp / (tp + fp + fn) if (tp + fp + fn) > 0 else 0.0\n",
                "        prec = tp / (tp + fp) if (tp + fp) > 0 else 0.0\n",
                "        rec = tp / (tp + fn) if (tp + fn) > 0 else 0.0\n",
                "        f1 = (2 * prec * rec) / (prec + rec) if (prec + rec) > 0 else 0.0\n",
                "        results[act] = {'iou': iou, 'f1': f1, 'prec': prec, 'rec': rec}\n",
                "        print(f'{act:<12} | {iou:<8.4f} | {f1:<8.4f} | {prec:<10.4f} | {rec:<8.4f}')\n",
                "    \n",
                "    tot_iou = tot_tp / (tot_tp + tot_fp + tot_fn) if (tot_tp + tot_fp + tot_fn) > 0 else 0.0\n",
                "    tot_prec = tot_tp / (tot_tp + tot_fp) if (tot_tp + tot_fp) > 0 else 0.0\n",
                "    tot_rec = tot_tp / (tot_tp + tot_fn) if (tot_tp + tot_fn) > 0 else 0.0\n",
                "    tot_f1 = (2 * tot_prec * tot_rec) / (tot_prec + tot_rec) if (tot_prec + tot_rec) > 0 else 0.0\n",
                "    print('-' * 56)\n",
                "    print(f'{\"OVERALL\":<12} | {tot_iou:<8.4f} | {tot_f1:<8.4f} | {tot_prec:<10.4f} | {tot_rec:<8.4f}\\n')\n",
                "    return results, {'iou': tot_iou, 'f1': tot_f1, 'prec': tot_prec, 'rec': tot_rec}\n"
